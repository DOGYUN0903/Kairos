-- 주문(애그리거트 루트), 판매자 주문, 주문 항목. member·seller·sku·product 는 ID 로만 참조한다(FK 없음).
-- order_item 의 상품명·브랜드명·옵션명·가격은 주문 시점 스냅샷이다. 인덱스는 PK/UNIQUE 만 둔다.
CREATE TABLE orders (
    id                    BIGINT       NOT NULL AUTO_INCREMENT,
    order_no              VARCHAR(32)  NOT NULL,
    member_id             BIGINT       NOT NULL,
    order_status          VARCHAR(20)  NOT NULL,
    receiver_name         VARCHAR(50)  NOT NULL,
    receiver_phone        VARCHAR(20)  NOT NULL,
    zip_code              VARCHAR(10)  NOT NULL,
    address1              VARCHAR(200) NOT NULL,
    address2              VARCHAR(200) NOT NULL,
    delivery_memo         VARCHAR(200) NULL,
    items_amount          BIGINT       NOT NULL,
    buyer_shipping_fee    BIGINT       NOT NULL,
    total_amount          BIGINT       NOT NULL,
    free_shipping_applied BIT          NOT NULL,
    shipping_fee_recovered BIGINT      NOT NULL,
    refunded_amount       BIGINT       NOT NULL,
    expires_at            DATETIME(6)  NOT NULL,
    paid_at               DATETIME(6)  NULL,
    created_at            DATETIME(6)  NOT NULL,
    created_by            BIGINT       NOT NULL,
    modified_at           DATETIME(6)  NOT NULL,
    modified_by           BIGINT       NOT NULL,
    status                VARCHAR(20)  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_orders_order_no UNIQUE (order_no)
);

CREATE TABLE seller_order (
    id                  BIGINT       NOT NULL AUTO_INCREMENT,
    order_id            BIGINT       NOT NULL,
    seller_id           BIGINT       NOT NULL,
    seller_name         VARCHAR(100) NOT NULL,
    commission_rate_bp  INT          NOT NULL,
    seller_order_status VARCHAR(20)  NOT NULL,
    shipping_fee        BIGINT       NOT NULL,
    shipping_fee_payer  VARCHAR(20)  NOT NULL,
    carrier_code        VARCHAR(20)  NULL,
    tracking_number     VARCHAR(50)  NULL,
    shipped_at          DATETIME(6)  NULL,
    delivered_at        DATETIME(6)  NULL,
    confirmed_at        DATETIME(6)  NULL,
    created_at          DATETIME(6)  NOT NULL,
    created_by          BIGINT       NOT NULL,
    modified_at         DATETIME(6)  NOT NULL,
    modified_by         BIGINT       NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE order_item (
    id                    BIGINT       NOT NULL AUTO_INCREMENT,
    seller_order_id       BIGINT       NOT NULL,
    sku_id                BIGINT       NOT NULL,
    product_id            BIGINT       NOT NULL,
    product_name          VARCHAR(100) NOT NULL,
    brand_name            VARCHAR(50)  NOT NULL,
    option_display_name   VARCHAR(120) NOT NULL,
    sale_price            BIGINT       NOT NULL,
    extra_price           BIGINT       NOT NULL,
    quantity              INT          NOT NULL,
    order_item_status     VARCHAR(20)  NOT NULL,
    cancel_actor          VARCHAR(20)  NULL,
    cancel_reason         VARCHAR(500) NULL,
    refund_amount         BIGINT       NOT NULL,
    shipping_fee_deducted BIGINT       NOT NULL,
    shipping_fee_returned BIGINT       NOT NULL,
    canceled_at           DATETIME(6)  NULL,
    created_at            DATETIME(6)  NOT NULL,
    created_by            BIGINT       NOT NULL,
    modified_at           DATETIME(6)  NOT NULL,
    modified_by           BIGINT       NOT NULL,
    status                VARCHAR(20)  NOT NULL,
    PRIMARY KEY (id)
);
